"""Radio cut: narration over placeholder music on a black screen (User Test #1).

Input:   storyboard.json, outputs/narration/*.wav, outputs/narration/timings.json
Output:  outputs/radio_cut/radio_cut.mp4 (+ radio_cut.srt)

Run:  python -m pipeline.radio_cut [--force]

Pure FFmpeg, deterministic: same inputs -> same file. Cached by a hash of the
storyboard timing/subtitles and the narration files' bytes, so it rebuilds
only when one of those changes. The placeholder music is a soft synthesized
E-minor drone (generated by FFmpeg), ducked under the voice with
sidechaincompress, and the mix is loudness-normalised to about -14 LUFS.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from pipeline import storyboard, subtitles
from pipeline.common import OUTPUTS, StageError, cached_call, file_hash

OUT_DIR = OUTPUTS / "radio_cut"
OUT_MP4 = OUT_DIR / "radio_cut.mp4"
OUT_SRT = OUT_DIR / "radio_cut.srt"
NARRATION_DIR = OUTPUTS / "narration"
END_CARD_SEC = storyboard.END_CARD_SEC
W, H, FPS = 720, 1280, 24

# Ducking settings from the challenge's starting point (Appendix B).
DUCK = {"threshold": 0.02, "ratio": 6, "attack": 300, "release": 1500}
LOUDNESS = {"I": -14, "TP": -1, "LRA": 11}

# Placeholder drone: E3, G3, B3 (E minor), slow swell, low-passed.
DRONE = ("0.10*(sin(2*PI*164.81*t)+0.8*sin(2*PI*196.00*t)+0.6*sin(2*PI*246.94*t)"
         "+0.3*sin(2*PI*82.41*t))*(0.65+0.35*sin(2*PI*0.08*t))")


def build_command(sb: dict, out: Path) -> list[str]:
    shots = sb["shots"]
    total = sum(float(s["duration_sec"]) for s in shots) + END_CARD_SEC
    inputs, parts, seg_labels = [], [], []

    for s in shots:
        dur = float(s["duration_sec"])
        wav = NARRATION_DIR / f"{s['id']}.wav"
        label = f"seg_{s['id']}"
        if s["narration"] and wav.exists():
            idx = len(inputs) // 2
            inputs += ["-i", str(wav)]
            delay_ms = int(subtitles.NARRATION_OFFSET_SEC * 1000)
            parts.append(f"[{idx}:a]aresample=48000,aformat=channel_layouts=mono,"
                         f"adelay={delay_ms},apad=whole_dur={dur},atrim=duration={dur}[{label}]")
        else:
            parts.append(f"anullsrc=r=48000:cl=mono,atrim=duration={dur}[{label}]")
        seg_labels.append(f"[{label}]")
    parts.append(f"anullsrc=r=48000:cl=mono,atrim=duration={END_CARD_SEC}[seg_end]")
    seg_labels.append("[seg_end]")

    n_audio = len(inputs) // 2
    music_idx, video_idx = n_audio, n_audio + 1
    inputs += ["-f", "lavfi", "-i", f"aevalsrc='{DRONE}':s=48000:d={total}"]
    inputs += ["-f", "lavfi", "-i", f"color=c=black:s={W}x{H}:r={FPS}:d={total}"]

    parts.append(f"{''.join(seg_labels)}concat=n={len(seg_labels)}:v=0:a=1[voice]")
    parts.append("[voice]asplit=2[voice_mix][voice_key]")
    parts.append(f"[{music_idx}:a]lowpass=f=1400,afade=t=in:d=2,"
                 f"afade=t=out:st={total - 3}:d=3,volume=0.6[music]")
    parts.append(f"[music][voice_key]sidechaincompress=threshold={DUCK['threshold']}:"
                 f"ratio={DUCK['ratio']}:attack={DUCK['attack']}:release={DUCK['release']}[ducked]")
    parts.append("[voice_mix][ducked]amix=inputs=2:duration=first:normalize=0,"
                 f"loudnorm=I={LOUDNESS['I']}:TP={LOUDNESS['TP']}:LRA={LOUDNESS['LRA']},"
                 "aresample=48000[aout]")
    # Subtitles: SRT is referenced by bare filename because FFmpeg runs in OUT_DIR
    # (avoids Windows drive-letter escaping in the filter string).
    parts.append(f"[{video_idx}:v]subtitles={OUT_SRT.name}:force_style="
                 "'FontName=Arial,FontSize=13,PrimaryColour=&H00FFFFFF,OutlineColour=&H00000000,"
                 "BorderStyle=1,Outline=1,Alignment=2,MarginV=120'[vout]")

    return ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *inputs,
            "-filter_complex", ";".join(parts),
            "-map", "[vout]", "-map", "[aout]",
            "-c:v", "libx264", "-preset", "veryfast", "-tune", "stillimage", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-b:a", "192k", "-t", f"{total}", "-movflags", "+faststart",
            out.name]


def run(force: bool = False) -> Path:
    sb = storyboard.load()
    timing_inputs = [{k: s[k] for k in ("id", "duration_sec", "narration", "subtitle")} for s in sb["shots"]]
    wav_hashes = {p.stem: file_hash(p) for p in sorted(NARRATION_DIR.glob("s*.wav"))}

    def build(out: Path) -> dict:
        subtitles.write_srt(OUT_SRT, subtitles.cues(sb))
        cmd = build_command(sb, out)
        proc = subprocess.run(cmd, cwd=out.parent, capture_output=True, text=True)
        if proc.returncode != 0:
            raise StageError(f"ffmpeg failed: {proc.stderr.strip()[-800:]}")
        return {"notes": f"{len(sb['shots'])} shots, placeholder drone, duck={DUCK}, loudnorm={LOUDNESS}"}

    r = cached_call(stage="radio_cut", shot_id=None, provider="local", model="ffmpeg",
                    parameters={"duck": DUCK, "loudness": LOUDNESS, "size": f"{W}x{H}", "drone": DRONE},
                    seed=None, inputs={"shots": timing_inputs, "narration_wavs": wav_hashes},
                    output=OUT_MP4, fn=build, max_attempts=1, force=force)
    print(f"radio cut: {r.status} in {r.latency_sec:.1f}s -> {OUT_MP4.relative_to(OUTPUTS.parent)}")
    return OUT_MP4


if __name__ == "__main__":
    try:
        run(force="--force" in sys.argv)
    except StageError as exc:
        print(f"FAILED: {exc}")
        sys.exit(1)
